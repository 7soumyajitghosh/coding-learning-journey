#include<stdio.h>
int main()
{
    int number = 25;
    char star = '*';
    int age = 24;
    age = 67;
    float pi = 3.14;
// we can write comments in c using /* and */
// we can write single line comments in c

    int a = 20;
    int A = 69;

    int _final = 14;
    int final_value = 15;
// we can use underscore in variable name but we cannot start variable

//  printing the values of variables
    printf("number: %d\n", number);
    printf("star: %c\n", star);
    printf("age: %d\n", age);
    printf("pi: %f\n", pi);
    printf("a: %d\n", a);
    printf("A: %d\n", A);
    printf("final: %d\n", _final);
    printf("final_value: %d\n", final_value);
    
    return 0;
}